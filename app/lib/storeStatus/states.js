/**
 * One vocabulary for release state across both stores. The raw store value always
 * travels with the normalized one, so nothing is lost in the mapping.
 */
const STATE = Object.freeze({
  DRAFT: 'DRAFT',
  WAITING_FOR_REVIEW: 'WAITING_FOR_REVIEW',
  IN_REVIEW: 'IN_REVIEW',
  REJECTED: 'REJECTED',
  APPROVED_PENDING_RELEASE: 'APPROVED_PENDING_RELEASE',
  LIVE: 'LIVE',
  SUPERSEDED: 'SUPERSEDED',
  OTHER: 'OTHER'
});

// App Store Connect `appVersionState` (the deprecated `appStoreState` is not used).
const APPLE_VERSION_STATE = Object.freeze({
  PREPARE_FOR_SUBMISSION: STATE.DRAFT,
  READY_FOR_REVIEW: STATE.DRAFT,
  DEVELOPER_REJECTED: STATE.DRAFT,
  WAITING_FOR_REVIEW: STATE.WAITING_FOR_REVIEW,
  WAITING_FOR_EXPORT_COMPLIANCE: STATE.WAITING_FOR_REVIEW,
  IN_REVIEW: STATE.IN_REVIEW,
  REJECTED: STATE.REJECTED,
  METADATA_REJECTED: STATE.REJECTED,
  INVALID_BINARY: STATE.REJECTED,
  ACCEPTED: STATE.APPROVED_PENDING_RELEASE,
  PENDING_DEVELOPER_RELEASE: STATE.APPROVED_PENDING_RELEASE,
  PENDING_APPLE_RELEASE: STATE.APPROVED_PENDING_RELEASE,
  PROCESSING_FOR_DISTRIBUTION: STATE.APPROVED_PENDING_RELEASE,
  READY_FOR_DISTRIBUTION: STATE.LIVE,
  REPLACED_WITH_NEW_VERSION: STATE.SUPERSEDED
});

const normalizeAppleVersionState = (raw) => APPLE_VERSION_STATE[raw] || STATE.OTHER;

// Google Play `releaseLifecycleState`, without its RELEASE_LIFECYCLE_STATE_ prefix.
const GOOGLE_STATE_PREFIX = 'RELEASE_LIFECYCLE_STATE_';
const GOOGLE_RELEASE_STATE = Object.freeze({
  DRAFT: STATE.DRAFT,
  NOT_SENT_FOR_REVIEW: STATE.DRAFT,
  IN_REVIEW: STATE.IN_REVIEW,
  APPROVED_NOT_PUBLISHED: STATE.APPROVED_PENDING_RELEASE,
  NOT_APPROVED: STATE.REJECTED,
  PUBLISHED: STATE.LIVE
});

const stripGoogleStatePrefix = (raw) => {
  if (typeof raw !== 'string' || !raw) return null;
  return raw.startsWith(GOOGLE_STATE_PREFIX) ? raw.slice(GOOGLE_STATE_PREFIX.length) : raw;
};

const normalizeGoogleReleaseState = (raw) => GOOGLE_RELEASE_STATE[stripGoogleStatePrefix(raw)] || STATE.OTHER;

module.exports = {
  STATE,
  APPLE_VERSION_STATE,
  normalizeAppleVersionState,
  GOOGLE_RELEASE_STATE,
  stripGoogleStatePrefix,
  normalizeGoogleReleaseState
};
